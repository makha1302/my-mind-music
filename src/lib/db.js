import Dexie from 'dexie'

// ฐานข้อมูลในเครื่อง (IndexedDB) — เป็นที่เก็บหลักของแอป คลาวด์มาทีหลังในขั้น 1.5
export const db = new Dexie('my-mind-music')

// สตริงในแต่ละตารางคือ "คีย์หลัก, ตามด้วยฟิลด์ที่อยากค้นหาได้เร็ว"
// ฟิลด์อื่นเก็บได้หมดโดยไม่ต้องประกาศ
// ถ้าจะเปลี่ยนโครงสร้างทีหลัง ให้เพิ่ม db.version(2) ห้ามแก้ version(1) ที่ใช้ไปแล้ว
db.version(1).stores({
  // ข้อมูลคลิป (ไม่มีไฟล์เสียงในนี้ จะได้โหลดรายการเร็ว)
  clips: 'id, sessionId, folderId, status, createdAt',
  // ชิ้นเสียงระหว่างอัด ชิ้นละประมาณ 1 วินาที ลบทิ้งหลังประกอบเป็นไฟล์เต็มแล้ว
  chunks: '++id, clipId',
  // ไฟล์เสียงเต็มของแต่ละคลิป แยกตารางไว้เพราะไฟล์ใหญ่
  audio: 'clipId',
})
